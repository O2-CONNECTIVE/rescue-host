package serviceprovision

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"strconv"
	"strings"
	"time"
)

// Quote every Unicode scalar with Rust escapes, never Go's incompatible \uXXXX.
// ASCII paths also escape backslashes/quotes; no input can terminate a literal.
func installationRustString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, c := range s {
		switch c {
		case '\\':
			b.WriteString("\\\\")
		case '"':
			b.WriteString("\\\"")
		default:
			if c >= 32 && c <= 126 {
				b.WriteRune(c)
			} else {
				fmt.Fprintf(&b, "\\u{%x}", c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
func installationRustBytes(data []byte) string {
	var b strings.Builder
	b.WriteString("&[")
	for i, v := range data {
		if i%24 == 0 {
			b.WriteString("\n        ")
		}
		b.WriteString(strconv.Itoa(int(v)))
		b.WriteByte(',')
	}
	b.WriteString("\n    ]")
	return b.String()
}
func installationRustSource(a Anchor, p UntrustedClientProjection, record []byte) string {
	sum := sha256.Sum256(record)
	digest := append([]byte(hex.EncodeToString(sum[:])), '\n')
	return fmt.Sprintf(`// Code generated by tether-service-client-manifest; DO NOT EDIT.
// Exact source pairing only; not installation protection or peer authentication.
use super::Seed;

pub(super) fn seed() -> Option<Seed> {
    Some(Seed {
        service_name: %s,
        service_sid: %s,
        operator_sid: %s,
        guest_sid: %s,
        record_path: %s,
        digest_path: %s,
        volume_root: %s,
        filesystem: %s,
        serial: %d,
        read_ms: %d,
        cleanup_ms: %d,
        record: %s,
        digest: %s,
    })
}
`, installationRustString(a.ServiceName), installationRustString(p.ServiceSID), installationRustString(p.OperatorSID), installationRustString(p.ExcludedGuestSID), installationRustString(a.RecordPath), installationRustString(a.DigestPath), installationRustString(a.Volume.Root), installationRustString(a.Volume.Filesystem), a.Volume.Serial, a.ReadTimeout/time.Millisecond, a.CleanupTimeout/time.Millisecond, installationRustBytes(record), installationRustBytes(digest))
}
