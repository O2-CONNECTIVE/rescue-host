package serviceprovision

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"strconv"
	"time"
	"unicode/utf8"

	"github.com/O2-CONNECTIVE/rescue-host/backend/internal/protectedkey"
)

// InstallationAnchorBytes bounds the reviewed, nonsecret offline input.
const InstallationAnchorBytes = 8192

type installationAnchorInput struct {
	Protocol    string                 `json:"protocol"`
	ServiceName string                 `json:"serviceName"`
	RecordPath  string                 `json:"recordPath"`
	DigestPath  string                 `json:"digestPath"`
	Volume      clientProjectionVolume `json:"volume"`
	ReadMs      string                 `json:"readMs"`
	CleanupMs   string                 `json:"cleanupMs"`
}

// decodeInstallationAnchor accepts exactly Marshal's canonical bytes plus LF.
// Exact reserialization rejects duplicate/unknown/case-folded fields, alternate
// numbers/escapes, whitespace and malformed Unicode before source emission.
func decodeInstallationAnchor(data []byte) (Anchor, error) {
	var w installationAnchorInput
	if len(data) == 0 || len(data) > InstallationAnchorBytes || !utf8.Valid(data) || !recordUnicode(data) || json.Unmarshal(data, &w) != nil {
		return Anchor{}, ErrRecord
	}
	encoded, err := json.Marshal(w)
	if err != nil || !bytes.Equal(data, append(encoded, '\n')) || w.Protocol != "rescue-installation-anchor/1" {
		return Anchor{}, ErrRecord
	}
	read, e1 := strconv.ParseUint(w.ReadMs, 10, 64)
	cleanup, e2 := strconv.ParseUint(w.CleanupMs, 10, 64)
	if e1 != nil || e2 != nil || read == 0 || read > 120000 || cleanup == 0 || cleanup > 120000 || strconv.FormatUint(read, 10) != w.ReadMs || strconv.FormatUint(cleanup, 10) != w.CleanupMs {
		return Anchor{}, ErrRecord
	}
	a := Anchor{ServiceName: w.ServiceName, RecordPath: w.RecordPath, DigestPath: w.DigestPath, Volume: protectedkey.VolumeProfile{Root: w.Volume.Root, Filesystem: w.Volume.Filesystem, Serial: w.Volume.Serial}, ReadTimeout: time.Duration(read) * time.Millisecond, CleanupTimeout: time.Duration(cleanup) * time.Millisecond}
	if a.Validate() != nil {
		return Anchor{}, ErrRecord
	}
	return a, nil
}

// EncodeInstallationAnchorSource is phase one, before selecting a service build.
// No record/build hashes enter the service source, avoiding a self-hash cycle.
func EncodeInstallationAnchorSource(input []byte) ([]byte, error) {
	a, err := decodeInstallationAnchor(input)
	if err != nil {
		return nil, err
	}
	return installationGoSource(a)
}
func installationGoSource(a Anchor) ([]byte, error) {
	source := fmt.Sprintf(`// Code generated by tether-service-client-manifest; DO NOT EDIT.
// Source pairing is not installation protection or build provenance.
package serviceprovision

import (
 "time"
 "github.com/O2-CONNECTIVE/rescue-host/backend/internal/protectedkey"
)
func fixedInstallationAnchor() Anchor {
 return Anchor{ServiceName:%q,RecordPath:%q,DigestPath:%q,
 Volume:protectedkey.VolumeProfile{Root:%q,Filesystem:%q,Serial:%d},
 ReadTimeout:%d*time.Millisecond,CleanupTimeout:%d*time.Millisecond}
}
`, a.ServiceName, a.RecordPath, a.DigestPath, a.Volume.Root, a.Volume.Filesystem, a.Volume.Serial, a.ReadTimeout/time.Millisecond, a.CleanupTimeout/time.Millisecond)
	return format.Source([]byte(source))
}

type installationSourcePair struct {
	Protocol       string `json:"protocol"`
	Trust          string `json:"trust"`
	GoAnchorSource string `json:"goAnchorSource"`
	RustSeedSource string `json:"rustSeedSource"`
}

// EncodeInstallationSourcePair validates phase one's selected source and the
// exact record/selected build pair. It neither attests compilation provenance
// nor authenticates a service, peer, installation or principal.
func EncodeInstallationSourcePair(input, selectedGo, recordBytes []byte, build [32]byte) ([]byte, error) {
	a, err := decodeInstallationAnchor(input)
	if err != nil {
		return nil, err
	}
	goSource, err := installationGoSource(a)
	if err != nil || !bytes.Equal(goSource, selectedGo) {
		return nil, ErrRecord
	}
	projection, err := DeriveUntrustedClientProjection(recordBytes, build)
	if err != nil || projection.ServiceName != a.ServiceName || projection.Volume != projectClientVolume(a.Volume) || projection.ServiceImage.Volume != projectClientVolume(a.Volume) {
		return nil, ErrRecord
	}
	rust := installationRustSource(a, projection, recordBytes)
	out, err := json.Marshal(installationSourcePair{Protocol: "rescue-installation-source-pair/1", Trust: "unverified", GoAnchorSource: string(goSource), RustSeedSource: rust})
	if err != nil {
		return nil, ErrRecord
	}
	return append(out, '\n'), nil
}
