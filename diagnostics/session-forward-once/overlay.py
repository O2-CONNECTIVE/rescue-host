"""Exact Git-backed LF/CRLF validation and private diagnostic overlays."""
import hashlib
import json
from pathlib import Path
import stat
import subprocess
import pins


SITES = frozenset(('unknown', 'checkout-root', 'checkout-head', 'checkout-tree',
    'tracked-source', 'untracked-source', 'generated-lifecycle', 'generated-structure',
    'generated-content', 'identity-boundary', 'identity-hash', 'identity-comparison', 'identity-write'))
GENERATED = {n: b.encode() for n, b in json.loads(
    Path(__file__).with_name('generated-permissions.json').read_text()).items()}
GENERATED_ROOT = 'ui/tauri/src-tauri/permissions/autogenerated'


class Rejection(ValueError):
    def __init__(self, site):
        super().__init__('FORWARD_SOURCE_REJECTED')
        self.site = site if site in SITES else 'unknown'


def need(value, site='unknown'):
    if not value:
        raise Rejection(site)


def generated_permissions(root, required):
    """Only the four pinned LF outputs; sequential checks, not an atomic lease."""
    need(type(required) is bool, 'generated-lifecycle')
    folder = root / GENERATED_ROOT
    # Reject symlinks/junctions/reparse points on every in-checkout directory.
    current = root
    for component in ('', *GENERATED_ROOT.split('/')[:-1]):
        if component: current = current / component
        try:
            info = current.lstat()
        except FileNotFoundError:
            need(not required, 'generated-lifecycle')
            return set()
        need(stat.S_ISDIR(info.st_mode) and not getattr(info, 'st_file_attributes', 0) & 1024,
             'generated-structure')
    permissions = current
    top = []
    for path in permissions.iterdir():
        top.append(path.name)
        need(len(top) <= 3, 'generated-structure')
    need(set(top) - {'autogenerated'} == {'shell.toml', 'resident-source.toml'}, 'generated-structure')
    for name in ('shell.toml', 'resident-source.toml'):
        blob(root, 'ui/tauri/src-tauri/permissions/' + name)
    if 'autogenerated' not in top:
        need(not required, 'generated-lifecycle')
        return set()
    info = folder.lstat()
    need(stat.S_ISDIR(info.st_mode) and not getattr(info, 'st_file_attributes', 0) & 1024,
         'generated-structure')
    need(required, 'generated-lifecycle')
    # Bound enumeration even for an unexpected directory; never publish names.
    entries = []
    for path in folder.iterdir():
        entries.append(path)
        need(len(entries) <= 4, 'generated-structure')
    need({p.name for p in entries} == set(GENERATED), 'generated-structure')
    for path in entries:
        info = path.lstat()
        need(stat.S_ISREG(info.st_mode) and info.st_nlink == 1 and
             not getattr(info, 'st_file_attributes', 0) & 1024, 'generated-structure')
        need(info.st_size == len(GENERATED[path.name]) and
             path.read_bytes() == GENERATED[path.name], 'generated-content')
    return {GENERATED_ROOT + '/' + n for n in GENERATED}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def git(root, *args, binary=False):
    data = subprocess.check_output(['git', '-C', str(root), *args], stderr=subprocess.DEVNULL, timeout=30)
    return data if binary else data.decode().strip()


def checkout(root, head, tree=None, product=False, generated=False):
    need(Path(git(root, 'rev-parse', '--show-toplevel')).resolve() == root.resolve(), 'checkout-root')
    need(git(root, 'rev-parse', 'HEAD') == head, 'checkout-head')
    if tree:
        need(git(root, 'rev-parse', 'HEAD^{tree}') == tree, 'checkout-tree')
    need(not git(root, 'status', '--porcelain', '--untracked-files=no'), 'tracked-source')
    outputs = generated_permissions(root, generated) if product else set()
    unknown = git(root, 'ls-files', '--others', '--exclude-standard').splitlines()
    need(not unknown or product and all(n in outputs or
         n.startswith(('.control/', '.diagnostic/')) for n in unknown), 'untracked-source')


def blob(root, name):
    canonical = git(root, 'show', 'HEAD:' + name, binary=True)
    file = root / name
    need(file.is_file() and not file.is_symlink())
    actual = file.read_bytes()
    need(actual == canonical or b'\r' not in canonical and actual == canonical.replace(b'\n', b'\r\n'))
    return canonical, actual


def setup_projection(data):
    text = data.decode()
    ending = '\r\n' if b'\r\n' in data else '\n'
    text = text.replace('\r\n', '\n')
    anchor = "if ($LASTEXITCODE -ne 0) { throw 'NATIVE_DIAGNOSTIC_PATCH_REJECTED' }\n"
    need(text.count(anchor) == 1)
    call = '& python "$env:FORWARD_CONTROL/diagnostics/session-forward-once/driver.py" '
    args = '--root "$env:FORWARD_ROOT" --source "$ToolsDirectory/tauri-driver-$($tools.tauriDriverVersion)" --archive $crate'
    text = text.replace(anchor, anchor + call + 'apply ' + args + '\n' +
                        "if ($LASTEXITCODE -ne 0) { throw 'NATIVE_CONNECTION_PREFLIGHT_REJECTED' }\n")
    old = '& python "$root/scripts/apply_driver_trace.py" --archive $crate --source "$ToolsDirectory/tauri-driver-$($tools.tauriDriverVersion)" --patch-folder "$root/tools/native-driver-trace" --provenance "$ToolsDirectory/driver-provenance.json" --verify-patched --binary "$ToolsDirectory/tauri/bin/tauri-driver.exe"'
    need(text.count(old) == 1)
    text = text.replace(old, call + 'verify ' + args + ' --binary "$ToolsDirectory/tauri/bin/tauri-driver.exe"')
    return text.replace('\n', ending).encode()


def supervisor_projection(data):
    old = b"$stageProvenance.variant -ne 'tauri-driver-2.1.0-stage-1'"
    need(data.count(old) == 1)
    return data.replace(old, b"$stageProvenance.variant -ne 'tauri-driver-2.1.0-connection-probe-1'")


def expected(source, diagnostic):
    files = {}
    names = git(source, 'ls-tree', '-r', '--name-only', 'HEAD', 'ui/tauri/native-smoke').splitlines()
    need(1 <= len(names) <= 80)
    for name in names:
        _, actual = blob(source, name)
        files[name] = actual
    files['ui/tauri/native-smoke/setup.ps1'] = setup_projection(files['ui/tauri/native-smoke/setup.ps1'])
    files['ui/tauri/native-smoke/supervise.ps1'] = supervisor_projection(files['ui/tauri/native-smoke/supervise.ps1'])
    names = ['scripts/apply_driver_trace.py'] + git(source, 'ls-tree', '-r', '--name-only', 'HEAD', 'tools/native-driver-trace').splitlines()
    for name in names:
        canonical, _ = blob(source, name)
        files[name] = canonical
    scope = {}
    names = git(diagnostic, 'ls-tree', '-r', '--name-only', 'HEAD', 'diagnostics/session-forward').splitlines()
    need(len(names) == 10)
    for name in names:
        canonical, _ = blob(diagnostic, name)
        scope[name] = canonical
    for name in ['scripts/apply_driver_trace.py', 'scripts/verify_driver_trace.py',
                 'scripts/verify_tauri_evaluation.py', 'scripts/package_tauri_evaluation.py',
                 *git(source, 'ls-tree', '-r', '--name-only', 'HEAD', 'tools/native-driver-trace').splitlines()]:
        scope[name] = blob(source, name)[0]
    return files, scope


def put(root, files):
    need(not root.exists())
    root.mkdir(parents=True)
    for name, data in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def verify(root, files):
    paths = list(root.rglob('*'))
    need(all(not p.is_symlink() and (p.is_file() or p.is_dir()) for p in paths))
    need({p.relative_to(root).as_posix() for p in paths if p.is_file()} == set(files))
    need(all((root / n).read_bytes() == b for n, b in files.items()))


def materialize(source, diagnostic, root, create=False, generated=False):
    checkout(source, pins.PRODUCT, pins.PRODUCT_TREE, True, generated)
    checkout(diagnostic, pins.DIAGNOSTIC, pins.DIAGNOSTIC_TREE)
    files, scope = expected(source, diagnostic)
    if create:
        put(root / 'overlay', files)
        put(root / 'diagnostic-scope', scope)
    verify(root / 'overlay', files)
    verify(root / 'diagnostic-scope', scope)
    return sha(b''.join(name.encode() + b'\0' + hashlib.sha256(data).digest() for name, data in sorted(files.items()))), len(files)
