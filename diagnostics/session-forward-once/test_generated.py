"""Synthetic generated outputs at the actual identity/recording seam; no build/native."""
import contextlib
import io
import json
import os
from pathlib import Path
import sys
import unittest
from unittest.mock import patch
import overlay
import pins
import publish
import runner
import test_once

GOLDEN = {n: b.encode() for n, b in json.loads(
    (Path(__file__).parent / 'generated-permissions.json').read_text()).items()}

class GeneratedTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        test_once.CheckoutTests.setUpClass()
        cls.fixture = test_once.CheckoutTests

    @classmethod
    def tearDownClass(cls):
        test_once.CheckoutTests.tearDownClass()

    def setUp(self):
        self.source = self.fixture.source
        self.root = self.fixture.base / 'pr231-connection-once'
        if self.root.exists():
            import shutil
            shutil.rmtree(self.root)
        self.generated = self.source / 'ui/tauri/src-tauri/permissions/autogenerated'
        if self.generated.exists() or self.generated.is_symlink():
            import shutil
            if self.generated.is_symlink(): self.generated.unlink()
            else: shutil.rmtree(self.generated)
        event = {'action': 'opened', 'pull_request': {'draft': True,
            'head': {'sha': self.fixture.control_sha, 'ref': pins.BRANCH,
                     'repo': {'full_name': 'O2-CONNECTIVE/rescue-host'}},
            'base': {'ref': pins.BASE, 'sha': pins.BASE_SHA}}}
        event_path = self.fixture.base / 'event-generated.json'
        event_path.write_text(json.dumps(event))
        self.env = {'GITHUB_EVENT_PATH': str(event_path), 'GITHUB_RUN_ATTEMPT': '1',
            'GITHUB_REPOSITORY': 'O2-CONNECTIVE/rescue-host', 'EXPECTED_CONTROL': self.fixture.control_sha,
            'GITHUB_WORKSPACE': str(self.source), 'RUNNER_TEMP': str(self.fixture.base),
            'RUNNER_ENVIRONMENT': 'github-hosted', 'RUNNER_OS': 'Windows', 'RUNNER_ARCH': 'X64',
            'GITHUB_STEP_SUMMARY': str(self.fixture.base / 'summary-generated.txt')}
        self.environment = patch.dict(os.environ, self.env)
        self.environment.start()
        self.addCleanup(self.environment.stop)
        runner.boundary(self.source, self.root, True)

    def outputs(self):
        self.generated.mkdir(parents=True)
        for name, data in GOLDEN.items():
            (self.generated / name).write_bytes(data)

    def built(self):
        # Synthetic successful command checkpoint; no compiler/process is invoked.
        value = {'schema': 1, 'commands': {name: {'state': 'not-run', 'exitCode': None,
            'outputContractVerified': None} for name in runner.COMMANDS}}
        value['commands']['product-build'] = {'state': 'succeeded', 'exitCode': 0,
                                              'outputContractVerified': True}
        runner.write(self.root / 'safe/command-ledger.json', value)

    def test_actual_identity_accepts_only_exact_complete_postbuild_outputs(self):
        runner.identity(self.source, self.root)
        self.outputs(); self.built()
        value = runner.identity(self.source, self.root)
        self.assertEqual(value['product'], pins.PRODUCT)
        self.assertEqual(set(overlay.GENERATED), {'get_shell_status.toml',
            'get_status_presentation.toml', 'get_resident_status.toml', 'request_resident_intent.toml'})
        self.assertEqual(overlay.GENERATED, GOLDEN)

    def test_outputs_before_successful_build_are_rejected(self):
        self.outputs()
        with self.assertRaises(ValueError): runner.identity(self.source, self.root)
        for state, code, verified in [('running', None, None), ('failed', 1, False),
                                       ('succeeded', 0, False)]:
            self.built()
            p = self.root / 'safe/command-ledger.json'; v = runner.read(p)
            v['commands']['product-build'].update(state=state, exitCode=code, outputContractVerified=verified)
            runner.write(p, v)
            with self.assertRaises(ValueError): runner.identity(self.source, self.root)

    def test_missing_partial_extra_mutated_and_crlf_outputs_reject(self):
        self.built()
        with self.assertRaises(ValueError): runner.identity(self.source, self.root)
        self.outputs(); first = self.generated / next(iter(GOLDEN)); original = first.read_bytes()
        for bad in (None, original + b'# SYNTHETIC_MUTATION\n', original.replace(b'\n', b'\r\n'),
                    b'\xef\xbb\xbf' + original, original[:-1]):
            if bad is None: first.unlink()
            else: first.write_bytes(bad)
            with self.assertRaises(ValueError): runner.identity(self.source, self.root)
            first.write_bytes(original)
        extra = self.generated / 'reference.md'; extra.write_text('SYNTHETIC_EXTRA')
        with self.assertRaises(ValueError): runner.identity(self.source, self.root)
        extra.unlink()
        nested = self.generated / 'nested'; nested.mkdir()
        with self.assertRaises(ValueError): runner.identity(self.source, self.root)
        nested.rmdir()

    def test_symlink_hardlink_and_directory_alias_reject(self):
        self.outputs(); self.built()
        first = self.generated / next(iter(GOLDEN)); original = first.read_bytes()
        target = self.fixture.base / 'synthetic-target'; target.write_bytes(original)
        first.unlink(); first.symlink_to(target)
        with self.assertRaises(ValueError): runner.identity(self.source, self.root)
        first.unlink(); os.link(target, first)
        with self.assertRaises(ValueError): runner.identity(self.source, self.root)
        first.unlink(); first.write_bytes(original)
        moved = self.generated.with_name('synthetic-moved'); self.generated.rename(moved)
        self.generated.symlink_to(moved, target_is_directory=True)
        try:
            with self.assertRaises(ValueError): runner.identity(self.source, self.root)
        finally:
            self.generated.unlink(); moved.rename(self.generated)
        # Synthetic Windows reparse flag at the same lstat call site.
        from types import SimpleNamespace
        real_lstat = Path.lstat
        def reparse(path, *args, **kwargs):
            info = real_lstat(path, *args, **kwargs)
            return SimpleNamespace(st_mode=info.st_mode, st_file_attributes=1024) if path == self.generated else info
        with patch.object(Path, 'lstat', autospec=True, side_effect=reparse):
            with self.assertRaises(ValueError): runner.identity(self.source, self.root)

    def test_unknown_and_tracked_source_mutations_still_reject(self):
        # Even Git-ignored ACL input locations must reject before Cargo can scan.
        for directory, name in [('build', 'extra.json'), ('gen', 'extra.toml')]:
            folder = self.source / 'ui/tauri/src-tauri/permissions' / directory
            folder.mkdir(); (folder / name).write_text('SYNTHETIC_ACL_INPUT')
            try:
                with self.assertRaises(ValueError): runner.identity(self.source, self.root)
            finally:
                (folder / name).unlink(); folder.rmdir()
        self.outputs(); self.built()
        unknown = self.source / 'SYNTHETIC_UNKNOWN'; unknown.write_text('SYNTHETIC')
        try:
            with self.assertRaises(ValueError): runner.identity(self.source, self.root)
        finally: unknown.unlink()
        tracked = self.source / 'ui/tauri/src-tauri/build.rs'; original = tracked.read_bytes()
        try:
            tracked.write_bytes(original + b'\n// SYNTHETIC_MUTATION\n')
            with self.assertRaises(ValueError): runner.identity(self.source, self.root)
        finally: tracked.write_bytes(original)

    def test_actual_rejection_sites_are_closed_and_first_failure_preserved(self):
        self.outputs(); self.built()
        first = self.generated / next(iter(GOLDEN)); first.write_bytes(b'SYNTHETIC_PRIVATE_VALUE')
        with self.assertRaises(ValueError): runner.identity(self.source, self.root)
        with self.assertRaises(ValueError): runner.identity(self.source, self.root, True)
        value = runner.read_rejections(self.root)
        self.assertEqual(value, {'schema': 1, 'stage': 'generated-content', 'finalIdentity': 'generated-content'})
        runner.record_rejection(self.root, 'stage', RuntimeError('SYNTHETIC_SECRET'), 'unknown')
        self.assertEqual(runner.read_rejections(self.root), value)
        for bad in ({**value, 'stage': 'SYNTHETIC_SECRET'}, {**value, 'extra': 1},
                    {**value, 'schema': True}, {**value, 'stage': 1}):
            with self.assertRaises(ValueError): runner.validate_rejections(bad)
        # Observe real hash/write catch sites without replacing the thrown object.
        first.write_bytes(GOLDEN[first.name])
        exe = self.source / 'ui/tauri/src-tauri/target/debug/rescue-host-shell.exe'
        exe.parent.mkdir(parents=True, exist_ok=True); exe.write_bytes(b'SYNTHETIC_NOT_EXECUTABLE')
        original_write = runner.write
        for site in ('identity-hash', 'identity-write'):
            (self.root / 'safe/rejection-sites.json').unlink()
            error = OSError('SYNTHETIC_PRIVATE_EXCEPTION')
            def fail_write(path, value):
                if path.name == 'build-identity.json': raise error
                return original_write(path, value)
            target = patch.object(runner.legacy, 'digest', side_effect=error) if site == 'identity-hash' else \
                patch.object(runner, 'write', side_effect=fail_write)
            with target, self.assertRaises(OSError) as caught:
                runner.identity(self.source, self.root)
            self.assertIs(caught.exception, error)
            self.assertEqual(runner.read_rejections(self.root)['stage'], site)
        exe.unlink()

    def test_boundary_rejection_stops_before_native_and_retains_partial_facts(self):
        self.outputs(); self.built()
        first = self.generated / next(iter(GOLDEN)); first.write_bytes(b'SYNTHETIC_PRIVATE_VALUE')
        state = {'schema': 1, 'stages': {s: 'passed' for s in runner.STAGES},
                 'nativeInvoked': False, 'auditInvoked': False}
        state['stages']['trial'] = 'not-run'; runner.write(self.root / 'safe/run-status.json', state)
        with patch.object(sys, 'argv', ['runner.py', 'trial', '--source', str(self.source), '--root', str(self.root)]), \
             patch.object(runner, 'perform') as perform, contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(runner.main(), 1)
            perform.assert_not_called()
        self.assertFalse(runner.read(self.root / 'safe/run-status.json')['nativeInvoked'])
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(publish.finalize(self.source, self.root), 1)
        files = json.loads((self.root / 'safe/canonical-record.json').read_text())['files']
        self.assertEqual(files['outcome.json']['rejectionSites']['stage'], 'generated-content')
        self.assertIn('command-ledger.json', files)
        self.assertNotIn('SYNTHETIC_PRIVATE_VALUE', json.dumps(files))

    def test_missing_malformed_conflicting_and_truncated_rejection_evidence_is_unknown(self):
        state = {'schema': 1, 'stages': {s: 'not-run' for s in runner.STAGES},
                 'nativeInvoked': False, 'auditInvoked': False}
        state['stages']['environment'] = 'failed'
        for data in (None, b'{', b' ' * 513,
                     b'{"schema":1,"stage":"tracked-source","stage":"unknown","finalIdentity":null}',
                     b'{"schema":1,"stage":"SYNTHETIC_SECRET","finalIdentity":null}'):
            p = self.root / 'safe/rejection-sites.json'
            if data is None:
                if p.exists(): p.unlink()
            else: p.write_bytes(data)
            facts, valid = runner.rejection_facts(self.root, state, True)
            self.assertFalse(valid); self.assertEqual(facts['stage'], 'unknown')
            self.assertNotIn('SYNTHETIC_SECRET', json.dumps(facts))


if __name__ == '__main__':
    unittest.main()
